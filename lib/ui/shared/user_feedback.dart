// Only reviewed messages may cross from storage, network or platform errors
// into the interface. Unknown errors use the caller's action-specific fallback.
String userError(Object? error, {required String fallback}) {
  final message = switch (error) {
    FormatException e => e.message,
    FileSystemException e => e.message,
    StateError e => e.message,
    PlatformException e => e.message,
    String value => value,
    _ => null,
  };
  final known = _messages[message];
  if (known != null) return known;
  if (message is String) {
    for (final entry in _operationErrors.entries) {
      if (message.startsWith(entry.key)) return entry.value;
    }
  }
  if (error is SocketException) return '离线';
  if (error is TimeoutException) return '离线';
  if (error is HandshakeException) return '无法验证设备，请重新绑定';
  if (error is FileSystemException) return '无法读写文件，请检查存储空间和权限';
  return fallback;
}

