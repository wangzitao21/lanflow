import 'package:flutter/material.dart';

/// Translates product copy at its rendering boundary. User-authored text must
/// stay outside this function; placeholders preserve names and content verbatim.
String tr(
  BuildContext context,
  String source, [
  Map<String, Object?>? values,
]) => translateProductText(
  source,
  language: Localizations.maybeLocaleOf(context)?.languageCode ?? 'zh',
  values: values,
);

String translateProductText(
  String source, {
  required String language,
  Map<String, Object?>? values,
}) {
  var result = source;
  if (language == 'en') {
    final exact = _english[source];
    result = exact ?? source;
    if (exact == null && values == null && _hasChinese.hasMatch(source)) {
      for (final template in _templates) {
        final match = template.pattern.firstMatch(source);
        if (match == null) continue;
        result = template.translation;
        for (var i = 0; i < template.names.length; i++) {
          result = result.replaceAll(
            '{${template.names[i]}}',
            template.names[i] == 'status' || template.names[i] == 'label'
                ? translateProductText(match.group(i + 1)!, language: language)
                : match.group(i + 1)!,
          );
        }
        break;
      }
    }
  }
  if (values != null) {
    for (final entry in values.entries) {
      result = result.replaceAll('{${entry.key}}', '${entry.value ?? ''}');
    }
  }
  return result;
}

final _hasChinese = RegExp(r'[\u4e00-\u9fff]');

final _templates = [
  for (final entry in _english.entries)
    if (entry.key.contains('{')) _TranslationTemplate(entry.key, entry.value),
];

class _TranslationTemplate {
  _TranslationTemplate(String source, this.translation) {
    final fields = RegExp(r'\{([a-zA-Z]+)\}').allMatches(source).toList();
    names = [for (final field in fields) field.group(1)!];
    final expression = StringBuffer('^');
    var offset = 0;
    for (final field in fields) {
      expression
        ..write(RegExp.escape(source.substring(offset, field.start)))
        ..write(
          ['count', 'total', 'percent'].contains(field.group(1))
              ? r'([0-9]+)'
              : '([\\s\\S]*?)',
        );
      offset = field.end;
    }
    expression
      ..write(RegExp.escape(source.substring(offset)))
      ..write(r'$');
    pattern = RegExp(expression.toString());
  }
  late final List<String> names;
  late final RegExp pattern;
  final String translation;
}

